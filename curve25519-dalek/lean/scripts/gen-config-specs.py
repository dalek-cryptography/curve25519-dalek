#!/usr/bin/env python3
"""Generate the per-configuration spec files from the hand-written `x86_64-tables` template.

curve25519-dalek is translated in four configurations (`x86_64-tables`, `i686-tables`,
`x86_64-no-tables`, `i686-no-tables`), and their specs are the same up to names. Each
`Specs/<File>.lean` states its per-configuration items once, for `x86_64-tables`, between the lines

    -- BEGIN PER-CONFIG
    -- END PER-CONFIG

and this script writes the other three configurations' copies to `Specs/<File>/<Config>.lean` by
renaming. Lines between `-- BEGIN TABLES-ONLY` and `-- END TABLES-ONLY` (items that exist only with
precomputed tables) are dropped from the `no-tables` copies.

    scripts/gen-config-specs.py           # regenerate
    scripts/gen-config-specs.py --check   # fail if a generated file is out of date (CI)
"""

import pathlib
import re
import sys

SPECS = pathlib.Path(__file__).resolve().parent.parent / "Specs"
TEMPLATE = "x86_64-tables"
CONFIGS = {
    "i686-tables": "I686Tables",
    "x86_64-no-tables": "X86_64NoTables",
    "i686-no-tables": "I686NoTables",
}


def rename(text: str, config: str) -> str:
    text = text.replace(TEMPLATE, config)
    if config.startswith("i686"):
        # The 32-bit backend: `u32` field elements and constants instead of `u64` ones.
        text = text.replace("FieldElement51", "FieldElement2625")
        text = text.replace("serial.u64.", "serial.u32.")
    return text


def generate(template: pathlib.Path, config: str) -> str:
    lines = template.read_text().split("\n")
    header_end = lines.index("public section")
    begin = lines.index("-- BEGIN PER-CONFIG")
    end = lines.index("-- END PER-CONFIG")
    body, skipping = [], False
    for line in lines[begin + 1 : end]:
        if line == "-- BEGIN TABLES-ONLY":
            skipping = config.endswith("no-tables")
            continue
        if line == "-- END TABLES-ONLY":
            skipping = False
            continue
        if not skipping:
            body.append(line)
    # Keep the imports and the `open`s of the template, drop its module docstring.
    imports = lines[: header_end + 1]
    preamble = [l for l in lines[header_end + 1 : begin] if l.startswith("open ")]
    out = (
        [f"-- AUTOGENERATED from {template.name} by `scripts/gen-config-specs.py`. Do not edit."]
        + imports
        + ["", f"/-! # `{template.stem}` specs for `{config}`, generated from `Specs/{template.name}` -/", ""]
        # Config names differ in length: the template's lines fit, the copies' may not.
        + ["set_option linter.style.longLine false", ""]
        + preamble
        + [""]
        + body
    )
    text = rename("\n".join(out), config)
    # Collapse the blank lines left where tables-only blocks were dropped.
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.rstrip("\n") + "\n"


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for template in sorted(SPECS.glob("*.lean")):
        if "-- BEGIN PER-CONFIG" not in template.read_text():
            continue
        for config, stem in CONFIGS.items():
            target = SPECS / template.stem / f"{stem}.lean"
            text = generate(template, config)
            if target.exists() and target.read_text() == text:
                continue
            stale.append(target)
            if not check:
                target.parent.mkdir(exist_ok=True)
                target.write_text(text)
    for target in stale:
        print(f"{'out of date' if check else 'wrote'}: {target.relative_to(SPECS.parent)}")
    return 1 if check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
